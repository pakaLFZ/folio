// Comment chat, following and resolving on its own copy of decks/example: an agent follows and watches, the
// user writes in the board's chat panel, the watch prints it and exits, the agent's reply appears live, the input bar
// stays pinned to the panel's bottom with a short and a long thread, unfollowing stops unread, Resolve moves the card
// to Done.
import { chromium } from "playwright";
import { spawn } from "node:child_process";
import { join } from "node:path";
import { bin, serve, until } from "./lib/server.mjs";
const server = await serve({ decks: ["example"] });
const { base, root, cli } = server;
const results = [];
const check = (name, ok, seen) => (results.push(ok), console.log(`${ok ? "PASS" : "FAIL"}  ${name}  ${seen}`));
const post = (path, body) => fetch(`${base}/${path}`, { method: "POST", body: JSON.stringify(body) }).then((r) => r.json());
const get = (path) => fetch(`${base}/${path}`).then((r) => r.json());
const a = server.token("example");
const c = await post(`${a}/comments`, { slide: "s002", region: [25, 110, 440, 100], marks: [], text: "Which barrier is right, 0.68 or 0.74 eV?" });
const followed = cli(["comment", "follow", c.id, "--worker", "w3"]);
check("an agent can follow a comment", /followed by user, w3/.test(followed), followed.trim());
const watch = spawn("node", [bin, "comment", "watch", c.id, "--worker", "w3", "--until-reply", "--timeout", "30"], { cwd: root });
let printed = "";
watch.stdout.on("data", (d) => (printed += d));
const exited = new Promise((r) => watch.on("exit", r));
await until(async () => (await get("api/streams")).streams >= 1);
const browser = await chromium.launch();
const page = await browser.newPage({ viewport: { width: 1440, height: 900 } });
page.on("pageerror", (e) => console.log("pageerror", e.message));
await page.goto(`${base}/inbox`, { waitUntil: "load" });
await page.locator(`li[data-card="${c.id}"] a`).click();
const panel = page.locator('aside[aria-label="Comment chat"]');
await panel.waitFor();
const header = panel.locator("header");
const headerLines = await header.locator("p").count();
const headerText = await header.innerText();
check("the panel's header is one line with no slot list or followers", headerLines === 1 && !/followed by/.test(headerText) && !/label:|fig:/.test(headerText), `header lines ${headerLines}, text ${JSON.stringify(headerText)}`);
const pinnedToBottom = async () => {
  const bar = panel.locator('[data-testid="input-bar"]');
  const [p, b] = await Promise.all([panel.boundingBox(), bar.boundingBox()]);
  return Math.abs(p.y + p.height - (b.y + b.height)) <= 16;
};
check("the input bar sits at the panel's bottom with a short thread", await pinnedToBottom(), `panel/bar gap ${JSON.stringify(await panel.boundingBox())} / ${JSON.stringify(await panel.locator('[data-testid="input-bar"]').boundingBox())}`);
const bar = panel.locator('[data-testid="input-bar"]');
const field = bar.locator("textarea");
const lines = () => field.evaluate((el) => ({ height: el.getBoundingClientRect().height, line: parseFloat(getComputedStyle(el).lineHeight) }));
const empty = await lines();
await field.fill("first\nsecond\nthird");
const three = await lines();
await field.fill("");
const cleared = await lines();
check("the board's chat is the input bar, one line until its text needs more", (await bar.count()) === 1 && Math.abs(empty.height - empty.line) <= 2 && Math.abs(three.height - 3 * three.line) <= 3 && Math.abs(cleared.height - cleared.line) <= 2, `bars ${await bar.count()}; empty ${empty.height}/${empty.line}, three lines ${three.height}, cleared ${cleared.height}`);
const sentBefore = (await get(`${a}/comments/${c.id}`)).thread.length;
await field.fill("Use 0.74 eV;");
await field.press("Shift+Enter");
const kept = await field.inputValue();
await field.fill("Use 0.74 eV; it is the Path B hop.");
await field.press("Enter");
const code = await Promise.race([exited, new Promise((r) => setTimeout(() => r("still running"), 10000))]);
const line = printed.trim().split("\n").filter(Boolean).map((l) => JSON.parse(l)).pop();
const afterSend = (await get(`${a}/comments/${c.id}`)).thread.length;
check("Shift+Enter breaks the line and does not send; Enter sends", afterSend === sentBefore + 1 && kept === "Use 0.74 eV;\n" && line?.text === "Use 0.74 eV; it is the Path B hop.", `messages ${sentBefore} -> ${afterSend} after Shift+Enter then Enter, field ${JSON.stringify(kept)}; Enter sent ${JSON.stringify(line?.text)}`);
check("watch --until-reply prints the user's message and exits", code === 0 && line?.author === "user" && line.text.startsWith("Use 0.74"), `exit ${code}; ${JSON.stringify(line)}`);
cli(["comment", "reply", c.id, "Done: the note now says 0.74 eV.", "--worker", "w3"]);
const live = await panel.getByText("Done: the note now says 0.74 eV.").waitFor({ timeout: 5000 }).then(() => true, () => false);
const leftSide = live ? await panel.locator("li", { hasText: "Done: the note now says" }).last().evaluate((el) => getComputedStyle(el).alignSelf) : "";
check("the agent's reply appears live, on the agent's side", live && leftSide === "flex-start", `shown ${live}, align ${leftSide}`);
await page.screenshot({ path: join(root, "chat-panel.png") });
for (let i = 0; i < 20; i++) cli(["comment", "reply", c.id, `Filler line ${i} to make the thread scroll.`, "--worker", "w3"]);
await panel.getByText("Filler line 19 to make the thread scroll.").waitFor({ timeout: 5000 });
check("the input bar sits at the panel's bottom with a long, scrolling thread", await pinnedToBottom(), `panel/bar gap ${JSON.stringify(await panel.boundingBox())} / ${JSON.stringify(await bar.boundingBox())}`);
cli(["comment", "unfollow", c.id, "--worker", "user"]);
await until(async () => !(await get(`${a}/comments/${c.id}`)).followers?.includes("user"));
await panel.getByRole("button", { name: "Close" }).click();
const before = (await (await fetch(`${base}/api/inbox?view=all`)).json()).unread;
cli(["comment", "reply", c.id, "One more note while unfollowed.", "--worker", "w3"]);
await page.locator(`li[data-card="${c.id}"]`, { hasText: "One more note while unfollowed." }).waitFor({ timeout: 5000 }).catch(() => {});
const after = await (await fetch(`${base}/api/inbox?view=all`)).json();
const row = after.rows.find((r) => r.id === c.id);
const dot = await page.locator(`li[data-card="${c.id}"] [aria-label$="unread"]`).count();
check("unfollowing stops the comment counting as unread", row.following === false && row.unread > 0 && after.unread === before && dot === 0, `following ${row.following}, its unread ${row.unread}, workspace unread ${before} -> ${after.unread}, dot ${dot}`);
await page.locator(`li[data-card="${c.id}"] a`).click();
await panel.waitFor();
const resolveBtn = panel.getByRole("button", { name: "Resolve" });
await resolveBtn.waitFor({ timeout: 5000 });
check("the panel's header carries a Resolve button, not a follow bell", (await resolveBtn.count()) === 1 && (await panel.getByRole("button", { name: /^(Follow|Unfollow)$/ }).count()) === 0, `resolve buttons ${await resolveBtn.count()}, follow buttons ${await panel.getByRole("button", { name: /^(Follow|Unfollow)$/ }).count()}`);
await resolveBtn.click();
await until(async () => (await get(`${a}/comments/${c.id}`)).status === "resolved");
const inDone = await page.locator(`section[aria-label="Done"] li[data-card="${c.id}"]`).waitFor({ timeout: 5000 }).then(() => true, () => false);
check("Resolve moves the card to Done", (await get(`${a}/comments/${c.id}`)).status === "resolved" && inDone, `status ${(await get(`${a}/comments/${c.id}`)).status}, seen in Done column ${inDone}`);
await browser.close();
watch.kill();
await server.stop();
console.log(`${results.filter(Boolean).length}/${results.length} passed`);
process.exit(results.every(Boolean) ? 0 : 1);
