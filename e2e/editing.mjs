// Browser check for in-place editing: a typed caption with bold and a subscript is saved as markup on
// blur; an edit made by a worker while the user types gives a conflict card, and "Keep mine" wins.
// Serves its own copy of decks/example-b.
import { chromium } from "playwright";
import { readFileSync } from "node:fs";
import { join } from "node:path";
import { serve, until } from "./lib/server.mjs";
const server = await serve({ decks: ["example-b"] });
const slideFile = join(server.deckDir("example-b"), "slides/s001.json");
const props = () => JSON.parse(readFileSync(slideFile, "utf8")).elements.s.props;
const caption = () => props().caption;
const results = [];
const check = (name, ok, seen) => (results.push(ok), console.log(`${ok ? "PASS" : "FAIL"}  ${name}  ${seen}`));
const workerSets = (slot, value) => server.cli(["patch", "decks/example-b/s001", "-", "--worker", "w9"], JSON.stringify([{ op: "add", path: `/elements/s/props/${slot}`, value }]));
const browser = await chromium.launch();
const page = await browser.newPage({ viewport: { width: 1440, height: 900 } });
page.on("pageerror", (e) => console.log("pageerror", e.message));
await page.goto(`${server.base}/${server.token("example-b")}/?slide=s001`, { waitUntil: "load" });
const slot = page.locator('main [data-slot="caption"] .folio-text');
const blur = () => page.locator("main").click({ position: { x: 5, y: 5 } });
const typed = "Uptake of **CO_{2}** is shown";
await slot.click();
await page.keyboard.press("ControlOrMeta+a");
await page.keyboard.type("Uptake of ");
await page.keyboard.press("ControlOrMeta+b");
await page.keyboard.type("CO");
await page.keyboard.press("ControlOrMeta+=");
await page.keyboard.type("2");
await page.keyboard.press("ControlOrMeta+=");
await page.keyboard.press("ControlOrMeta+b");
await page.keyboard.type(" is shown");
await blur();
const saved = await until(() => caption() === typed && caption());
check("bold and subscript are saved as markup on blur", saved === typed, JSON.stringify(caption()));
await slot.click();
await page.keyboard.press("End");
await page.keyboard.type(" by the user");
workerSets("caption", "Changed by worker w9");
await blur();
const card = await page.locator("text=was changed elsewhere").waitFor({ timeout: 5000 }).then(() => true, () => false);
check("a worker's edit to the slot being typed gives a conflict card", card && caption() === "Changed by worker w9", `card ${card}, file holds ${JSON.stringify(caption())}`);
await page.getByRole("button", { name: "Keep mine" }).click();
const mine = await until(() => caption() === `${typed} by the user`);
check("Keep mine writes the user's text", !!mine, JSON.stringify(caption()));
await slot.click();
await page.keyboard.press("End");
await page.keyboard.type(" again");
workerSets("title", "TITLE BY WORKER");
await blur();
const both = await until(() => props().title === "TITLE BY WORKER" && caption().endsWith(" again"));
const cards = await page.locator("text=was changed elsewhere").count();
check("an edit to another slot keeps both, with no conflict card", !!both && cards === 0, `title ${JSON.stringify(props().title)}, caption ${JSON.stringify(caption())}, conflict cards ${cards}`);
await browser.close();
await server.stop();
console.log(`${results.filter(Boolean).length}/${results.length} passed`);
process.exit(results.every(Boolean) ? 0 : 1);
