// Inbox checks against its own copies of decks/example and decks/example-b.
import { chromium } from "playwright";
import { existsSync, readdirSync } from "node:fs";
import { join } from "node:path";
import { serve, until } from "./lib/server.mjs";
const server = await serve();
const { base, cli } = server;
const results = [];
const check = (name, ok, seen) => (results.push(ok), console.log(`${ok ? "PASS" : "FAIL"}  ${name}  ${seen}`));
const post = (path, body) => fetch(`${base}/${path}`, { method: "POST", body: JSON.stringify(body) }).then((r) => r.json());
const get = (path) => fetch(`${base}/${path}`).then((r) => r.json());
const a = server.token("example");
const b = server.token("example-b");
const c1 = await post(`${a}/comments`, { slide: "s002", region: [25, 100, 440, 120], marks: [{ tool: "rect", points: [[40, 120], [300, 180]] }], text: "Shorten the first paragraph." });
const c2 = await post(`${b}/comments`, { slide: "s001", region: null, marks: [{ tool: "arrow", points: [[600, 300], [500, 200]] }], text: "Is this figure final?" });
await until(async () => (await get(`${a}/comments/${c1.id}`)).shots && (await get(`${b}/comments/${c2.id}`)).shots, 20000);
cli(["comment", "reply", c1.id, "Shortened it to two sentences.", "--worker", "w1"]);
const browser = await chromium.launch();
const page = await browser.newPage({ viewport: { width: 1300, height: 850 } });
page.on("pageerror", (e) => console.log("pageerror", e.message));
await page.goto(`${base}/inbox`, { waitUntil: "load" });
await page.waitForSelector(`text=Shortened it to two sentences.`);
const both = (await page.locator(`a[href*="comment=${c1.id}"]`).count()) === 1 && (await page.locator(`a[href*="comment=${c2.id}"]`).count()) === 1;
check("comments from two decks appear in the inbox", both, `${c1.id} in ${a}, ${c2.id} in ${b}`);
const dot = await page.locator(`li[data-card="${c1.id}"] [aria-label$="unread"]`).count();
check("an agent reply sets the unread dot", dot === 1, `unread dots on ${c1.id}: ${dot}`);
const cliRows = JSON.parse(cli(["inbox", "--json", "--status", "open"])).rows.map((r) => r.id).sort();
const pageRows = (await (await fetch(`${base}/api/inbox?view=open`)).json()).rows.filter((r) => r.view !== "drafts").map((r) => r.id).sort();
check("folio inbox --json matches the page", JSON.stringify(cliRows) === JSON.stringify(pageRows), `${cliRows.length} rows each`);
await page.goto(`${base}/inbox`, { waitUntil: "load" });
await page.locator(`li[data-card="${c1.id}"] a`).click();
await page.getByRole("link", { name: "Open on its slide" }).click();
await page.waitForURL(/comment=/);
const opened = new URL(page.url());
const plainAddress = opened.pathname === `/${a}/` && opened.search === `?slide=s002&comment=${c1.id}`;
const threadOpen = await page.waitForSelector("text=Shortened it to two sentences.", { timeout: 5000 }).then(() => true, () => false);
await page.locator("main svg rect[stroke-dasharray]").waitFor({ timeout: 10000 }).catch(() => {});
const mode = await page.locator('[data-chrome="mode"]').getByRole("radio", { name: /Edit/ }).getAttribute("aria-checked");
const pins = await page.locator("main [data-pin]").count();
const regionsShown = await page.locator("main svg rect[stroke-dasharray]").count();
const walk = (await page.getByRole("link", { name: "Inbox", exact: true }).count()) + (await page.getByRole("button", { name: /^(Previous|Next) comment$/ }).count());
check("the open button goes to the slide address in Edit with the thread, its region drawn, no pin and no walk pill", plainAddress && threadOpen && mode === "true" && walk === 0 && pins === 0 && regionsShown === 1, `pins ${pins}, regions ${regionsShown}, address ${opened.pathname}${opened.search}, thread ${threadOpen}, edit mode ${mode}, walk controls ${walk}`);
await page.goBack({ waitUntil: "load" });
const backOnBoard = new URL(page.url()).pathname === "/inbox" && (await page.locator(`li[data-card="${c1.id}"]`).waitFor({ timeout: 5000 }).then(() => true, () => false));
check("Back returns to the board", backOnBoard, `back at ${page.url()}`);
await page.goForward({ waitUntil: "load" });
const rowOf = async () => (await get("api/inbox?view=open")).rows.find((r) => r.id === c1.id);
await until(async () => (await rowOf())?.unread === 0);
const rowAfter = await rowOf();
check("opening a comment marks it read", rowAfter?.unread === 0, `unread now ${rowAfter?.unread}`);

cli(["patch", "decks/example/s002", "-", "--worker", "w1"], JSON.stringify([{ op: "add", path: "/elements/s/props/label:a", value: `(a) Energy profile of each window, ${new Date().toISOString().slice(11, 19)}` }]));
cli(["comment", "reply", c1.id, "Also reworded the label.", "--worker", "w1"]);
await until(async () => (await get(`${a}/comments/${c1.id}`)).thread.at(-1)?.shots, 20000);
await page.reload({ waitUntil: "load" });
await page.waitForSelector("text=Also reworded the label.", { timeout: 5000 }).catch(() => {});
const hasThen = await page.getByRole("radio", { name: "Then" }).count();
check("a changed slide shows no Then/Now history control", hasThen === 0, `Then radios found ${hasThen}`);

await page.goto(`${base}/${b}/?slide=s001`, { waitUntil: "load" });
await page.getByRole("radio", { name: /^Region/ }).click();
const box = await page.locator("main .folio-slide").boundingBox();
const k = box.width / 960;
await page.mouse.move(box.x + 100 * k, box.y + 100 * k);
await page.mouse.down();
await page.mouse.move(box.x + 300 * k, box.y + 200 * k, { steps: 5 });
await page.mouse.up();
await page.locator('[aria-label="New comment"] :is(textarea, input:not([type=file]))').first().fill("Half-written thought about the title");
await until(async () => (await get(`${b}/drafts`)).drafts.some((d) => d.text === "Half-written thought about the title" && d.region), 10000);
await page.goto(`${base}/inbox`, { waitUntil: "load" });
await page.locator('section[aria-label="Drafts"]').waitFor();
const draftToggles = await page.getByRole("button", { name: /^Drafts/ }).count();
check("drafts are a column, with no Drafts toggle on the bar", draftToggles === 0, `Drafts buttons ${draftToggles}`);
const draftLink = page.locator('section[aria-label="Drafts"] li:has-text("Half-written thought about the title") a[href*="draft="]').last();
await draftLink.waitFor({ timeout: 5000 });
const draftId = new URL(await draftLink.getAttribute("href"), base).searchParams.get("draft");
await draftLink.click();
await page.waitForURL(/draft=/);
await page.waitForFunction(() => document.querySelector('[aria-label="New comment"] :is(textarea, input:not([type=file]))')?.value, null, { timeout: 5000 }).catch(() => {});
const restored = await page.locator('[aria-label="New comment"] :is(textarea, input:not([type=file]))').first().inputValue().catch(() => "");
const region = await page.locator("main svg rect[stroke-dasharray]").count();
check("a draft reopens with its text and region", restored === "Half-written thought about the title" && region >= 1, `text "${restored}", region drawn ${region}`);

await page.goto(`${base}/inbox`, { waitUntil: "load" });
const draftCard = page.locator(`section[aria-label="Drafts"] li:has(a[href*="draft=${draftId}"])`);
await draftCard.waitFor({ timeout: 5000 });
await draftCard.hover();
await draftCard.getByRole("button", { name: "Discard draft" }).click();
const cardGone = await draftCard.waitFor({ state: "detached", timeout: 5000 }).then(() => true, () => false);
const stillListed = (await (await fetch(`${base}/${b}/drafts`)).json()).drafts.some((d) => d.id === draftId);
const draftsRoot = join(server.deckDir("example-b"), ".folio/drafts");
const archivedDraft = existsSync(draftsRoot) && readdirSync(draftsRoot).some((user) => existsSync(join(draftsRoot, user, ".archive", new Date().toISOString().slice(0, 10), `${draftId}.json`)));
check("Discard draft moves the draft to the drafts archive", cardGone && !stillListed && archivedDraft, `card gone ${cardGone}, still listed ${stillListed}, archived ${archivedDraft}`);

await post("api/inbox/bulk", { items: [{ deck: a, id: c1.id }, { deck: b, id: c2.id }], action: "resolve" });
const day = new Date().toISOString().slice(0, 10);
const archived = [join(server.deckDir("example"), "comments/.archive", day, `${c1.id}.json`), join(server.deckDir("example-b"), "comments/.archive", day, `${c2.id}.json`)].every(existsSync);
check("bulk resolve archives both", archived, `${c1.id}, ${c2.id}`);
await browser.close();
await server.stop();
console.log(JSON.stringify({ a, b, c1: c1.id, c2: c2.id }));
console.log(`${results.filter(Boolean).length}/${results.length} passed`);
process.exit(results.every(Boolean) ? 0 : 1);
