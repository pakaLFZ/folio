// Comment checks against its own copy of decks/example:
// region over note and figure, sketch, attachment, screenshots, status table, worker reply live, resolve to archive.
import { chromium } from "playwright";
import { existsSync, readdirSync, readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";
import { serve, until } from "./lib/server.mjs";
import { still } from "./lib/page.mjs";
const server = await serve({ decks: ["example"] });
const { base, root, cli } = server;
const deck = server.deckDir("example");
const token = server.token("example");
const results = [];
const check = (name, ok, seen) => (results.push(ok), console.log(`${ok ? "PASS" : "FAIL"}  ${name}  ${seen}`));
const browser = await chromium.launch();
const page = await browser.newPage({ viewport: { width: 1440, height: 900 } });
page.on("pageerror", (e) => console.log("pageerror", e.message));
await page.goto(`${base}/${token}/?slide=s002`, { waitUntil: "load" });
check("Edit is the default mode and the Cursor tool the default tool", (await page.locator('[data-chrome="mode"]').getByRole("radio", { name: /Edit/ }).getAttribute("aria-checked")) === "true" && (await page.getByRole("radio", { name: /^Edit text/ }).getAttribute("aria-checked")) === "true", "mode or tool not checked");
await page.keyboard.press("r");
await page.getByRole("radio", { name: /^Region/, checked: true }).waitFor({ timeout: 3000 }).catch(() => {});
check("R outside a text slot picks the Region tool", (await page.getByRole("radio", { name: /^Region/ }).getAttribute("aria-checked")) === "true", "Region not checked after R");
const slide = await page.locator("main .folio-slide").boundingBox();
const s = slide.width / 960;
const at = (x, y) => [slide.x + x * s, slide.y + y * s];
const bubble = page.locator('[role="dialog"][aria-label="New comment"]');
const selection = () => page.locator("main svg rect[stroke-dasharray]").first().boundingBox();
const meet = (a, b) => a.x < b.x + b.width && b.x < a.x + a.width && a.y < b.y + b.height && b.y < a.y + a.height;
const onScreen = (b, w, h) => b.x >= 0 && b.y >= 0 && b.x + b.width <= w && b.y + b.height <= h;
const drag = async (p, a, b) => (await p.mouse.move(...a), await p.mouse.down(), await p.mouse.move(...b, { steps: 6 }), await p.mouse.up());
const timeBubble = (p) => p.evaluate(() => {
  window.__bubble = new Promise((done) => addEventListener("pointerup", () => {
    const up = performance.now();
    const seen = () => (document.querySelector('[role="dialog"][aria-label="New comment"]') ? done(performance.now() - up) : requestAnimationFrame(seen));
    seen();
  }, { once: true, capture: true }));
});
await timeBubble(page);
await drag(page, at(120, 80), at(260, 140));
const opened = await page.evaluate(() => window.__bubble);
check("the bubble opens within 200 ms of the release", opened < 200, `${opened.toFixed(0)} ms`);
const first = await bubble.boundingBox();
const focused = await page.evaluate(() => { const a = document.activeElement; return !!a?.closest('[aria-label="New comment"]') && /TEXTAREA|INPUT/.test(a.tagName); });
check("the bubble's text field has focus", focused, await page.evaluate(() => document.activeElement?.tagName));
const bar = await bubble.locator('[data-testid="input-bar"]').boundingBox();
const cardParts = (await bubble.getByRole("button", { name: /Discard/ }).count()) + (await bubble.getByText(/^Region/).count()) + (await bubble.locator("svg[aria-hidden].absolute").count());
const bare = !!bar && Math.abs(bar.width - first.width) < 1 && Math.abs(bar.height - first.height) < 1 && (await bubble.evaluate((el) => !el.classList.contains("glass") && getComputedStyle(el).backgroundColor === "rgba(0, 0, 0, 0)"));
check("the new-comment input is the bare input bar: no card, head line, close button or pointer", bare && cardParts === 0, `bar ${JSON.stringify(bar)} wrapper ${JSON.stringify(first)}; card parts ${cardParts}`);
const floatingShadow = await bubble.locator('[data-testid="input-bar"] > div').first().evaluate((el) => getComputedStyle(el).boxShadow);
check("the floating bubble's bar carries a shadow", floatingShadow !== "none", floatingShadow);
await page.keyboard.type("The note and the plot disagree on the barrier; use the plot's value.");
await drag(page, at(300, 300), at(600, 360));
const [sel, moved] = [await selection(), await bubble.boundingBox()];
const kept = await bubble.locator("textarea, input:not([type=file])").first().inputValue();
check("a redrawn region moves the bubble and keeps the text", moved.y !== first.y && kept.startsWith("The note and the plot"), `top ${first.y.toFixed(0)} -> ${moved.y.toFixed(0)}`);
check("the bubble does not cover the selection at 1440x900", !meet(sel, moved), `bubble ${JSON.stringify(moved)} selection ${JSON.stringify(sel)}`);
check("the bubble is fully on screen at 1440x900", onScreen(moved, 1440, 900), JSON.stringify(moved));
await page.screenshot({ path: join(root, "comment-bubble.png") });
await page.getByRole("radio", { name: "Arrow (A)" }).click();
check("drawing tools hide the input bar without losing its draft", !(await bubble.isVisible()), "after choosing Arrow");
await drag(page, at(700, 250), at(560, 330));
await page.getByRole("radio", { name: /^Region/ }).click();
await bubble.waitFor();
check("selecting the region brings back the existing text", (await bubble.locator("textarea, input:not([type=file])").first().inputValue()).startsWith("The note and the plot"), "draft restored");
const attachment = join(root, "attach-test.csv");
writeFileSync(attachment, "x,y\n0,0\n1,0.68\n");
await bubble.locator('input[type="file"]').setInputFiles(attachment);
await page.waitForSelector("text=attach-test.csv");
await bubble.getByRole("button", { name: "Send" }).click();
const closed = await bubble.waitFor({ state: "detached", timeout: 3000 }).then(() => true, () => false);
const latest = () => {
  const files = readdirSync(join(deck, "comments")).filter((f) => f.endsWith(".json"));
  return files.length ? JSON.parse(readFileSync(join(deck, "comments", files.sort().pop()), "utf8")) : null;
};
const shotsOf = (c) => !!c?.shots && existsSync(join(deck, "comments", c.id, c.shots.region)) && existsSync(join(deck, "comments", c.id, c.shots.slide));
const comment = (await until(() => shotsOf(latest()) && latest(), 20000)) ?? latest();
const slots = comment.components.map((c) => c.slot);
check("Send creates the comment with the region and closes the bubble", closed && comment.region?.[0] === 300 && comment.region?.[2] === 300, `closed ${closed}, region ${JSON.stringify(comment.region)}`);
check("the comment lists both slots under the region", slots.includes("note") && slots.includes("fig:a"), slots.join(", "));
check("both screenshots exist", shotsOf(comment), JSON.stringify(comment.shots));
check("the sketch and the attachment are kept", comment.marks.length === 1 && comment.marks[0].tool === "arrow" && comment.thread[0].attachments?.[0]?.name === "attach-test.csv", `${comment.marks.length} mark(s); attachment ${comment.thread[0].attachments?.[0]?.file}`);
const thread = page.locator(`aside li[data-comment="${comment.id}"]`);
const closedBars = await thread.locator('[data-testid="input-bar"]').count();
check("a sent comment opens closed, with no 'Message the agent' bar", closedBars === 0, `bars ${closedBars}`);
const firstBubble = thread.getByRole("button", { name: "The note and the plot disagree" });
await firstBubble.click();
await thread.locator('[data-testid="input-bar"]').waitFor();
const status = cli(["status", "decks/example"]);
check("folio status prints the comment first", status.trimStart().startsWith("1 open comment") && status.includes(comment.id), status.split("\n")[0]);
writeFileSync(join(root, "attach-reply.txt"), "barrier taken from the plot\n");
cli(["comment", "reply", comment.id, "Changed the note to 0.74 eV", "--worker", "w1", "--attach", join(root, "attach-reply.txt")]);
const live = await page.waitForSelector("text=Changed the note to 0.74 eV", { timeout: 5000 }).then(() => true, () => false);
check("a worker's reply appears in the browser live", live, `attachment chip shown: ${await page.locator("text=attach-reply.txt").count()}`);
await page.screenshot({ path: join(root, "comment-thread.png") });
const replyBars = await thread.locator('[data-testid="input-bar"]').count();
const metaLines = await thread.getByText(/\d{1,2}:\d{2}/).count();
check("the selected issue's reply is the input bar, and messages carry no visible time", replyBars === 1 && metaLines === 0, `bars in the thread ${replyBars}, visible times ${metaLines}`);
const dockedReplyShadow = await thread.locator('[data-testid="input-bar"] > div').first().evaluate((el) => getComputedStyle(el).boxShadow);
check("the docked reply bar carries no shadow", dockedReplyShadow === "none", dockedReplyShadow);
const headerParts = (await thread.getByRole("button", { name: /^(Follow|Unfollow)$/ }).count()) + (await thread.getByText(/^(waiting on agent|your turn)$/).count());
const card = await thread.boundingBox();
const send = await thread.getByRole("button", { name: "Send", exact: true }).boundingBox();
const bubbleBox = await firstBubble.boundingBox();
check("an issue is its first message as a bubble, no header row, and Send inside the card", !!bubbleBox && headerParts === 0 && !!send && !!card && send.x + send.width <= card.x + card.width + 0.5, `bell or status ${headerParts}; send right ${send && send.x + send.width}, card right ${card && card.x + card.width}`);
const regions = () => page.locator("main svg rect[stroke-dasharray]").count();
const regionsReach = (n) => until(async () => (await regions()) === n, 3000);
const pinsInComment = await page.locator("main [data-pin]").count();
const regionSelected = await regions();
await firstBubble.click();
await regionsReach(0);
const regionNone = await regions();
await firstBubble.click();
await regionsReach(1);
check("only the selected issue's region is drawn, and no pin", pinsInComment === 0 && regionSelected === 1 && regionNone === 0 && (await regions()) === 1, `pins ${pinsInComment}; regions selected ${regionSelected}, none selected ${regionNone}`);
await thread.click({ position: { x: card.width - 6, y: 6 } });
await regionsReach(0);
const regionOffCardSpace = await regions();
check("clicking empty card space toggles the issue off, like the bubble does", regionOffCardSpace === 0, `regions ${regionOffCardSpace}`);
await thread.click({ position: { x: card.width - 6, y: 6 } });
await regionsReach(1);
const regionOnCardSpace = await regions();
check("clicking the same empty card space re-selects it", regionOnCardSpace === 1, `regions ${regionOnCardSpace}`);
const regionImg = thread.locator("img").first();
const [popup] = await Promise.all([page.waitForEvent("popup", { timeout: 1000 }).catch(() => null), regionImg.click()]);
await regionsReach(0);
const regionAfterImgClick = await regions();
check("clicking the region screenshot does not open it, only toggles the card", popup === null && regionAfterImgClick === 0, `popup ${popup ? "opened" : "none"}; regions ${regionAfterImgClick}`);
await regionImg.click();
await regionsReach(1);
check("clicking the image again re-selects the card", (await regions()) === 1, `regions ${await regions()}`);
await firstBubble.click();
await regionsReach(0);
cli(["comment", "reply", comment.id, "dont use fog. no fog pls", "--worker", "w1"]);
const bell = thread.locator('[aria-label="New reply"]');
await bell.waitFor({ timeout: 5000 });
check("a reply on a closed card shows the unread bell", await bell.isVisible(), "bell did not appear");
await firstBubble.click();
await thread.locator('[data-testid="input-bar"]').waitFor();
const bellGone = await until(async () => (await bell.count()) === 0, 3000);
check("opening the card clears the unread bell", bellGone, `bells left ${await bell.count()}`);
await page.getByRole("radio", { name: /^Edit text/ }).click();
const pinsInEdit = await page.locator("main [data-pin]").count();
const regionsInEdit = await regions();
const badgesInEdit = await page.locator("main .folio-slide [data-slot]:has(> .folio-text) > :not(.folio-text)").count();
await page.locator('[data-chrome="mode"]').getByRole("radio", { name: /View/ }).click();
const regionsInView = await regions();
const outlinesInView = await page.locator("main .folio-slide [data-slot]").evaluateAll((els) => els.filter((el) => getComputedStyle(el).outlineStyle !== "none").length);
const viewThread = page.locator(`aside li[data-comment="${comment.id}"]`);
const listedInView = await viewThread.count();
const writableInView = (await viewThread.locator('[data-testid="input-bar"]').count()) + (await viewThread.getByRole("button", { name: "Resolve", exact: true }).count());
await page.locator('[data-chrome="mode"]').getByRole("radio", { name: /Edit/ }).click();
check("Edit (Cursor tool) draws the selected region and no pin or badge; View draws no region or slot outline and the list is read-only", pinsInEdit === 0 && regionsInEdit === 1 && badgesInEdit === 0 && regionsInView === 0 && outlinesInView === 0 && listedInView === 1 && writableInView === 0, `edit: ${pinsInEdit} pins, ${regionsInEdit} regions, ${badgesInEdit} badges; view: ${regionsInView} regions, ${outlinesInView} outlined slots, issue listed ${listedInView}, ${writableInView} bars or Resolve`);
await viewThread.hover();
await viewThread.getByRole("button", { name: "Resolve", exact: true }).click();
const day = new Date().toISOString().slice(0, 10);
const archived = (id) => existsSync(join(deck, "comments/.archive", day, `${id}.json`)) && !existsSync(join(deck, "comments", `${id}.json`));
await until(() => archived(comment.id));
await viewThread.waitFor({ state: "detached", timeout: 5000 }).catch(() => {});
// New-comment input bar at the top of the Comments tab.
const tab = page.locator("aside").filter({ has: page.getByPlaceholder("New comment on this slide") });
check("with no comments the tab shows only the input bar, no 'No comments' text", (await tab.locator("li[data-comment]").count()) === 0 && (await tab.getByText("No comments on this slide.").count()) === 0 && (await tab.getByPlaceholder("New comment on this slide").count()) === 1, `issues ${await tab.locator("li[data-comment]").count()}`);
await tab.getByPlaceholder("New comment on this slide").fill("Whole-slide note: check the legend colour.");
await tab.getByRole("button", { name: "Send", exact: true }).first().click();
const slideComment = await page.waitForFunction(() => document.querySelectorAll('aside li[data-comment]').length === 1).then(() => tab.locator("li[data-comment]").first());
const slideCid = await slideComment.getAttribute("data-comment");
const slideFiles = (await until(() => { const f = readdirSync(join(deck, "comments")).filter((n) => n.endsWith(".json") && n.startsWith(slideCid)); return f.length ? f : null; })) ?? [];
const slideCommentFile = JSON.parse(readFileSync(join(deck, "comments", slideFiles.find((f) => f.startsWith(slideCid))), "utf8"));
check("the top bar's comment has no agent-drawn region: the whole slide's box", slideCommentFile.region?.[0] === 0 && slideCommentFile.region?.[1] === 0 && slideCommentFile.region?.[2] === 960 && slideCommentFile.region?.[3] === 540, JSON.stringify(slideCommentFile.region));
const [barBox, cardBox] = [await tab.getByPlaceholder("New comment on this slide").locator("xpath=ancestor::*[@data-testid='input-bar']").boundingBox(), await slideComment.boundingBox()];
check("the new comment appears at once and the bar lines up with the issue cards", (await tab.locator("li[data-comment]").count()) === 1 && Math.abs(barBox.x - cardBox.x) < 1 && Math.abs(barBox.x + barBox.width - (cardBox.x + cardBox.width)) < 1, `bar [${barBox.x.toFixed(1)}, ${(barBox.x + barBox.width).toFixed(1)}], card [${cardBox.x.toFixed(1)}, ${(cardBox.x + cardBox.width).toFixed(1)}]`);
await page.locator('[data-chrome="mode"]').getByRole("radio", { name: /View/ }).click();
check("View mode hides the new-comment input bar", (await page.getByPlaceholder("New comment on this slide").count()) === 0, String(await page.getByPlaceholder("New comment on this slide").count()));
await page.locator('[data-chrome="mode"]').getByRole("radio", { name: /Edit/ }).click();
await tab.locator(`li[data-comment="${slideCid}"]`).hover();
await tab.locator(`li[data-comment="${slideCid}"]`).getByRole("button", { name: "Resolve", exact: true }).click();
await until(() => archived(slideCid));
await page.getByRole("radio", { name: /^Edit text/ }).click();
const regionsBeforeEditDrag = await page.locator("main svg rect[stroke-dasharray]").count();
await drag(page, at(100, 100), at(200, 160));
check("with the Cursor tool a drag on the slide draws no region and opens no bubble", (await page.locator("main svg rect[stroke-dasharray]").count()) === regionsBeforeEditDrag && !(await bubble.isVisible()), "a region or bubble appeared");
await page.getByRole("radio", { name: /^Region/ }).click();
await drag(page, at(100, 100), at(200, 160));
await bubble.waitFor();
const regionsBefore = await page.locator("main svg rect[stroke-dasharray]").count();
await page.keyboard.press("Escape");
const discarded = await bubble.waitFor({ state: "detached", timeout: 2000 }).then(() => true, () => false);
const regionsAfter = await page.locator("main svg rect[stroke-dasharray]").count();
check("Esc discards the bubble and its region", discarded && regionsAfter === regionsBefore - 1, `bubble gone ${discarded}, regions ${regionsBefore} -> ${regionsAfter}`);
check("discarding returns the tool to Cursor", (await page.getByRole("radio", { name: /^Edit text/ }).getAttribute("aria-checked")) === "true", "Cursor not checked after Esc");
const awayPoint = [slide.x + 8, slide.y + slide.height + 8];
await page.getByRole("radio", { name: /^Region/ }).click();
await drag(page, at(100, 100), at(200, 160));
await bubble.waitFor();
const regionsDrawn = await regions();
await page.mouse.click(...awayPoint);
const awayDiscarded = await bubble.waitFor({ state: "detached", timeout: 2000 }).then(() => true, () => false);
check("a click away with an empty bar discards the draft and its region", awayDiscarded && (await regions()) === regionsDrawn - 1, `bubble gone ${awayDiscarded}, regions ${regionsDrawn} -> ${await regions()}`);
const openIds = async () => (await (await fetch(`${base}/${token}/comments`)).json()).comments.filter((c) => c.status !== "resolved").map((c) => c.id);
const idsBefore = await openIds();
await page.getByRole("radio", { name: /^Region/ }).click();
await drag(page, at(100, 100), at(200, 160));
await bubble.waitFor();
await page.keyboard.type("Sent by clicking away");
await page.mouse.click(...awayPoint);
const awaySent = await bubble.waitFor({ state: "detached", timeout: 3000 }).then(() => true, () => false);
const madeAway = (await openIds()).filter((id) => !idsBefore.includes(id));
const awayComment = madeAway.length === 1 ? JSON.parse(readFileSync(join(deck, "comments", `${madeAway[0]}.json`), "utf8")) : null;
check("a click away with text sends the comment", awaySent && awayComment?.thread[0]?.text === "Sent by clicking away", `bubble gone ${awaySent}, new comments ${madeAway.join(", ")}`);
for (const id of madeAway) await fetch(`${base}/${token}/comments/${id}/status`, { method: "POST", body: JSON.stringify({ status: "resolved" }) });
const phone = await browser.newPage({ viewport: { width: 390, height: 844 } });
await phone.goto(`${base}/${token}/?slide=s002&mode=comment`, { waitUntil: "load" });
await phone.getByRole("radio", { name: /^Edit text/, checked: true }).waitFor();
await phone.keyboard.press("r");
await phone.getByRole("radio", { name: /^Region/, checked: true }).waitFor();
await still(phone);
const small = await phone.locator("main .folio-slide").boundingBox();
const k = small.width / 960;
await drag(phone, [small.x + 300 * k, small.y + 200 * k], [small.x + 600 * k, small.y + 300 * k]);
const sheet = phone.locator('[role="dialog"][aria-label="New comment"]');
await sheet.waitFor({ timeout: 2000 });
const [phoneSel, phoneBox] = [await phone.locator("main svg rect[stroke-dasharray]").first().boundingBox(), await sheet.boundingBox()];
check("at 390x844 the bubble is on screen and off the selection", onScreen(phoneBox, 390, 844) && !meet(phoneSel, phoneBox), `bubble ${JSON.stringify(phoneBox)}`);
await phone.screenshot({ path: join(root, "comment-bubble-phone.png") });
await phone.keyboard.press("Escape");
await sheet.waitFor({ state: "detached", timeout: 2000 });
check("Resolve moves the comment to the archive", archived(comment.id), `comments/.archive/${day}/${comment.id}.json`);
await browser.close();
await server.stop();
console.log(`${results.filter(Boolean).length}/${results.length} passed`);
process.exit(results.every(Boolean) ? 0 : 1);
